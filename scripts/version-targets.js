'use strict';

/**
 * Every file that carries the package version besides package.json.
 * check-versions.js verifies them; stamp-version.js rewrites them.
 */

// [file, path to the version inside the parsed JSON]
// Only files a harness or this repo's own checks read. Audited 2026-10-13
// against vendor docs and the Claude Code, Codex, Copilot, and Grok CLIs; the
// metadata files nothing consumed were deleted (see CHANGELOG).
const JSON_TARGETS = [
  ['manifest.json', ['version']],
  ['rdap-q-skill/manifest.json', ['version']],
  ['plugin.json', ['version']],
  ['plugins/rdap-q/plugin.json', ['version']],
  ['.claude-plugin/plugin.json', ['version']],
  ['.claude-plugin/marketplace.json', ['plugins', 0, 'version']],
  ['.claude-plugin/plugin-index.json', ['plugins', 'rdap-q', 'version']],
];

// Every semver in these files must be the package version.
const PROSE_TARGETS = [
  'README.md',
  'AGENTS.md',
  'CLAUDE.md',
  'GEMINI.md',
  '.clinerules',
  '.goosehints',
  'bridges/grok/rules.md',
  'bridges/claude/commands/rdapq.md',
  '.github/copilot-instructions.md',
  'rdap-q-skill/SKILL.md',
  'rdap-q-skill/README.md',
  // Generated by scripts/sync-integrations.js; stamping it keeps it in step until the next sync.
  'integrations/hermes/SKILL.md',
  // The rdapq-nat pip package ships with the engine it wraps.
  'integrations/nemo/pyproject.toml',
];

// These must not hardcode a version; they read package.json at runtime.
// lib/hermes.js renders the Hermes frontmatter `version:` from package.json
// at install time, so the installed Hermes SKILL.md needs no stamp here.
// install.sh and install.ps1 do name the minimum Node.js major ("22"): they
// check Node before it can read package.json. That is not a semver, so the
// stamp checks ignore it; check-versions.js compares it with engines.node.
const NO_VERSION = ['bin/rdapq.js', 'lib/installer.js', 'lib/hermes.js', 'install.sh', 'install.ps1'];

// The installer wrappers that gate on the minimum Node.js major.
const NODE_GATES = ['install.sh', 'install.ps1'];

const SEMVER = /(?<![\d.])\d+\.\d+\.\d+(?![\d.])/g;

// A prose line carrying this marker may name other versions (release history,
// eval baselines). stamp-version leaves it alone and check-versions skips it.
const KEEP = '<!-- keep-version -->';
const stampable = (text) => text.split('\n').filter((line) => !line.includes(KEEP)).join('\n');

function pick(data, keys) {
  return keys.reduce((node, key) => (node == null ? undefined : node[key]), data);
}

module.exports = { JSON_TARGETS, PROSE_TARGETS, NO_VERSION, NODE_GATES, SEMVER, KEEP, stampable, pick };
